CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE app_user (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           varchar(254) NOT NULL UNIQUE,
    display_name    varchar(60)  NOT NULL,
    password_hash   varchar(255) NOT NULL,
    encrypted_phone text,
    role            varchar(20)  NOT NULL CHECK (role IN ('BUYER', 'SELLER', 'MODERATOR')),
    adult_declared  boolean      NOT NULL,
    verified_at     timestamptz,
    status          varchar(30)  NOT NULL,
    created_at      timestamptz  NOT NULL
);

CREATE TABLE verification_token (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint      NOT NULL REFERENCES app_user (id),
    token      varchar(64) NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    used_at    timestamptz
);

CREATE TABLE consent (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint      NOT NULL REFERENCES app_user (id),
    type       varchar(30) NOT NULL CHECK (type IN ('TERMS', 'LOCATION', 'NOTIFICATIONS')),
    granted_at timestamptz NOT NULL,
    revoked_at timestamptz
);

CREATE TABLE device (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint       NOT NULL REFERENCES app_user (id),
    push_token    varchar(512) NOT NULL UNIQUE,
    platform      varchar(20)  NOT NULL,
    registered_at timestamptz  NOT NULL
);

CREATE TABLE pickup_point (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id              bigint           NOT NULL REFERENCES app_user (id),
    alias                  varchar(40)      NOT NULL,
    encrypted_address      text             NOT NULL,
    encrypted_instructions text,
    encrypted_lat          text             NOT NULL,
    encrypted_lon          text             NOT NULL,
    cell_lat               double precision NOT NULL,
    cell_lon               double precision NOT NULL,
    cell_center            geography(Point, 4326)
        GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(cell_lon, cell_lat), 4326)::geography) STORED,
    created_at             timestamptz      NOT NULL
);
CREATE INDEX pickup_point_cell_gist ON pickup_point USING GIST (cell_center);

CREATE TABLE offer (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id          bigint       NOT NULL REFERENCES app_user (id),
    pickup_point_id    bigint       NOT NULL REFERENCES pickup_point (id),
    title              varchar(80)  NOT NULL,
    description        varchar(300),
    category           varchar(30)  NOT NULL,
    photo_key          varchar(200),
    base_price         integer      NOT NULL CHECK (base_price > 0 AND base_price % 100 = 0),
    min_price          integer      NOT NULL CHECK (min_price % 100 = 0),
    total_portions     integer      NOT NULL CHECK (total_portions BETWEEN 1 AND 50),
    available_portions integer      NOT NULL,
    prepared_at        timestamptz  NOT NULL,
    published_at       timestamptz  NOT NULL,
    expires_at         timestamptz  NOT NULL,
    closed_at          timestamptz,
    status             varchar(20)  NOT NULL,
    CONSTRAINT offer_price_range CHECK (min_price <= base_price AND min_price * 2 >= base_price),
    CONSTRAINT offer_stock CHECK (available_portions BETWEEN 0 AND total_portions),
    CONSTRAINT offer_duration CHECK (expires_at <= prepared_at + interval '210 minutes')
);
CREATE INDEX offer_status_expires ON offer (status, expires_at);
CREATE INDEX offer_seller ON offer (seller_id);

CREATE TABLE offer_allergen (
    offer_id bigint      NOT NULL REFERENCES offer (id) ON DELETE CASCADE,
    allergen varchar(30) NOT NULL,
    PRIMARY KEY (offer_id, allergen)
);

CREATE TABLE purchase_request (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id         bigint       NOT NULL REFERENCES offer (id),
    seller_id        bigint       NOT NULL REFERENCES app_user (id),
    buyer_id         bigint       NOT NULL REFERENCES app_user (id),
    portions         integer      NOT NULL CHECK (portions BETWEEN 1 AND 5),
    rounds           integer      NOT NULL CHECK (rounds BETWEEN 0 AND 3),
    current_price    integer      NOT NULL,
    current_party    varchar(20)  NOT NULL,
    status           varchar(20)  NOT NULL,
    close_reason     varchar(100),
    offer_expires_at timestamptz  NOT NULL,
    created_at       timestamptz  NOT NULL,
    updated_at       timestamptz  NOT NULL
);
CREATE UNIQUE INDEX purchase_request_single_open ON purchase_request (offer_id, buyer_id)
    WHERE status IN ('OFFER_SENT', 'COUNTEROFFER');
CREATE INDEX purchase_request_seller ON purchase_request (seller_id, status);
CREATE INDEX purchase_request_expiration ON purchase_request (status, offer_expires_at);

CREATE TABLE proposal (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint      NOT NULL REFERENCES purchase_request (id),
    party      varchar(20) NOT NULL,
    unit_price integer     NOT NULL CHECK (unit_price > 0 AND unit_price % 100 = 0),
    created_at timestamptz NOT NULL
);
CREATE INDEX proposal_request ON proposal (request_id);

CREATE TABLE orders (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id          bigint      NOT NULL UNIQUE REFERENCES purchase_request (id),
    offer_id            bigint      NOT NULL REFERENCES offer (id),
    buyer_id            bigint      NOT NULL REFERENCES app_user (id),
    seller_id           bigint      NOT NULL REFERENCES app_user (id),
    agreed_price        integer     NOT NULL,
    portions            integer     NOT NULL,
    status              varchar(20) NOT NULL,
    accepted_at         timestamptz NOT NULL,
    ready_at            timestamptz,
    delivered_at        timestamptz,
    cancelled_by        bigint REFERENCES app_user (id),
    cancellation_reason varchar(200),
    cancelled_at        timestamptz,
    window_end          timestamptz NOT NULL,
    code_hmac           varchar(64),
    code_attempts       integer     NOT NULL DEFAULT 0 CHECK (code_attempts BETWEEN 0 AND 5),
    code_issues         integer     NOT NULL DEFAULT 0 CHECK (code_issues BETWEEN 0 AND 2),
    CONSTRAINT orders_time_order CHECK (delivered_at IS NULL OR accepted_at <= delivered_at)
);
CREATE INDEX orders_buyer ON orders (buyer_id);
CREATE INDEX orders_seller ON orders (seller_id);
CREATE INDEX orders_window ON orders (status, window_end);

CREATE TABLE report (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id    bigint      NOT NULL REFERENCES offer (id),
    seller_id   bigint      NOT NULL REFERENCES app_user (id),
    reporter_id bigint      NOT NULL REFERENCES app_user (id),
    reason      varchar(30) NOT NULL,
    detail      varchar(300),
    resolved    boolean     NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL,
    CONSTRAINT report_single UNIQUE (offer_id, reporter_id)
);

CREATE TABLE rating (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     bigint      NOT NULL REFERENCES orders (id),
    author_id    bigint      NOT NULL REFERENCES app_user (id),
    recipient_id bigint      NOT NULL REFERENCES app_user (id),
    score        integer     NOT NULL CHECK (score BETWEEN 1 AND 5),
    created_at   timestamptz NOT NULL,
    CONSTRAINT rating_single UNIQUE (order_id, author_id)
);

CREATE TABLE audit_event (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    bigint,
    action      varchar(60) NOT NULL,
    entity      varchar(30) NOT NULL,
    entity_id   bigint,
    detail      varchar(300),
    occurred_at timestamptz NOT NULL
);
CREATE INDEX audit_event_occurred ON audit_event (occurred_at);
