ALTER TABLE app_user ADD COLUMN deletion_requested_at timestamptz;

ALTER TABLE consent ADD COLUMN text_version varchar(20) NOT NULL DEFAULT 'v1';
ALTER TABLE consent ADD CONSTRAINT consent_revoked_after_granted CHECK (revoked_at IS NULL OR revoked_at >= granted_at);
CREATE UNIQUE INDEX consent_single_active ON consent (user_id, type) WHERE revoked_at IS NULL;

CREATE TABLE refresh_token (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint      NOT NULL REFERENCES app_user (id),
    family_id  varchar(36) NOT NULL,
    token_hash varchar(64) NOT NULL UNIQUE,
    created_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz
);
CREATE INDEX refresh_token_user ON refresh_token (user_id);
CREATE INDEX refresh_token_family ON refresh_token (family_id);
CREATE INDEX refresh_token_expires ON refresh_token (expires_at);

CREATE INDEX rating_recipient ON rating (recipient_id);
